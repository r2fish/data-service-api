"""Projects `spec/data-service-api.v1.json`'s `endpoints`/`control_endpoints`
entries into `spec/OPERATION_CATALOG.json`, a derived, machine-readable
operation catalog (contract 1.7.0, subordinate ruling 12, R-8).

This is a PURE STRUCTURAL PROJECTION -- it reads the `roles` /
`requires_capability` / `atomicity` fields the contract JSON itself carries
on every `endpoints.*` / `control_endpoints.*` entry (added in 1.7.0
alongside the pre-existing `method` / `path` / `auth` / `request` /
`response` / `semantics` keys) and re-shapes them into one record per
operation. `destructive` is likewise derived structurally: it is the set of
bare `endpoint` names `destructive_confirmation.applies_to_structured`
lists (its trailing `{"note": ...}` element names no endpoint and is
ignored), never a hand-maintained name set and never a `semantics`-prose
inspection. It never interprets natural-language prose (design principle
A-7): `semantics`/`auth`/`description` text is not parsed or summarized
anywhere in this file.

Output is deterministic: a fixed field order per record (matching this
docstring's own listing), records sorted by `name`, `indent=2`,
`ensure_ascii=False`, and a trailing newline -- so re-running this script
against an unchanged contract reproduces `spec/OPERATION_CATALOG.json`
byte-for-byte (`conformance-tests/test_operation_catalog_register.py`
regenerates and diffs it on every run).

Standard library only (tools/ convention, `docs/work-orders/
WORK_ORDER_PHASE9_CONTRACT_170_V1.md` §2 WP-1 (7)).

Usage:
    ./.venv/bin/python tools/contract_catalog.py [--check]

Without --check, (re)writes spec/OPERATION_CATALOG.json. With --check, exits
non-zero (and prints a diff-free message identifying mismatch) if the
checked-in file is not byte-identical to a fresh run -- used by the register
test instead of shelling out, but also usable standalone from the CLI.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CONTRACT_PATH = REPO_ROOT / "spec" / "data-service-api.v1.json"
CATALOG_PATH = REPO_ROOT / "spec" / "OPERATION_CATALOG.json"

# Destructive operations -- read structurally from
# destructive_confirmation.applies_to_structured (the bare `endpoint` name
# each structured element names), never by inspecting `semantics` prose and
# never via a hand-maintained set of names. Elements that carry no
# `endpoint` key at all (the trailing `{"note": ...}` element) name no
# endpoint and are ignored.
def _destructive_endpoint_names(contract: dict) -> set[str]:
    names = set()
    for element in contract["destructive_confirmation"]["applies_to_structured"]:
        endpoint = element.get("endpoint")
        if endpoint is not None:
            names.add(endpoint)
    return names


def _endpoint_record(name: str, raw_name: str, entry: dict, *, destructive_names: set[str]) -> dict:
    return {
        "name": name,
        "method": entry["method"],
        "path": entry["path"],
        "roles": list(entry["roles"]),
        "requires_capability": list(entry["requires_capability"]),
        "atomicity": entry["atomicity"],
        "destructive": raw_name in destructive_names,
        "request_schema": entry.get("request"),
        "response_schema": entry.get("response"),
    }


def build_catalog(contract: dict) -> dict:
    destructive_names = _destructive_endpoint_names(contract)
    records = []
    for name, entry in contract["endpoints"].items():
        records.append(_endpoint_record(name, name, entry, destructive_names=destructive_names))
    for name, entry in contract["control_endpoints"].items():
        # audit_query exists in both sections under the same name; the
        # catalog keys operations by (section, name) to keep them distinct.
        # `raw_name` (unqualified) is what destructive_confirmation.
        # applies_to_structured names, so destructiveness is looked up by
        # the bare name even though the record's own `name` carries the
        # `control.` qualifier.
        records.append(_endpoint_record(f"control.{name}", name, entry, destructive_names=destructive_names))
    records.sort(key=lambda r: r["name"])
    return {
        "$comment": (
            "Generated by tools/contract_catalog.py from spec/data-service-api.v1.json. "
            "Do not hand-edit; re-run the generator instead."
        ),
        "contract_version": contract["contract_version"],
        "operations": records,
    }


def render(catalog: dict) -> str:
    return json.dumps(catalog, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def main(argv: list[str]) -> int:
    check_only = "--check" in argv
    contract = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    catalog = build_catalog(contract)
    rendered = render(catalog)

    if check_only:
        current = CATALOG_PATH.read_text(encoding="utf-8") if CATALOG_PATH.exists() else None
        if current == rendered:
            print(f"{CATALOG_PATH} is up to date.")
            return 0
        print(f"{CATALOG_PATH} is STALE -- re-run without --check to regenerate.")
        return 1

    CATALOG_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {CATALOG_PATH} ({len(catalog['operations'])} operations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
